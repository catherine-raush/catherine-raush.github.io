const SUPPORTED_LANGS = ["de", "ru", "en"];
const DEFAULT_LANG = "de";

/* ====================================================
   HELPERS
==================================================== */
function safeGet(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
}
function safeSet(key, value) {
    try { localStorage.setItem(key, value); } catch (e) { /* ignore */ }
}

function getLang() {
    const stored = safeGet("lang");
    if (SUPPORTED_LANGS.includes(stored)) return stored;

    const navLang = (navigator.language || DEFAULT_LANG).slice(0, 2).toLowerCase();
    return SUPPORTED_LANGS.includes(navLang) ? navLang : DEFAULT_LANG;
}

function setLang(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;

    safeSet("lang", lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.dataset.i18n;
        const value = translations[lang] && translations[lang][key];
        if (value != null) el.innerHTML = value;
    });

    document.querySelectorAll("[data-lang]").forEach(btn => {
        btn.classList.toggle("active", btn.dataset.lang === lang);
    });

    // Обновляем title и description
    document.title = metaTitles[lang] || metaTitles[DEFAULT_LANG];

    const descMeta = document.querySelector('meta[name="description"]');
    if (descMeta) {
        descMeta.setAttribute("content", metaDescriptions[lang] || metaDescriptions[DEFAULT_LANG]);
    }

    // Обновляем OG-теги (для корректного шаринга на текущем языке)
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", metaTitles[lang] || metaTitles[DEFAULT_LANG]);

    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute("content", metaDescriptions[lang] || metaDescriptions[DEFAULT_LANG]);

    const ogLocale = document.querySelector('meta[property="og:locale"]');
    if (ogLocale) {
        const locales = { de: "de_DE", ru: "ru_RU", en: "en_US" };
        ogLocale.setAttribute("content", locales[lang] || "de_DE");
    }
}

/* ====================================================
   REVEAL ANIMATION
==================================================== */
const prefersReducedMotion =
    window.matchMedia("(prefers-reduced-motion: reduce)").matches;

if (!prefersReducedMotion && "IntersectionObserver" in window) {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add("show");
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.15 });

    document.querySelectorAll("section.hidden").forEach(el => observer.observe(el));
} else {
    document.querySelectorAll("section.hidden").forEach(el => el.classList.remove("hidden"));
}

/* ====================================================
   NAV / SCROLL
==================================================== */
const nav = document.querySelector("nav");
const progressBar = document.querySelector(".scroll-progress");
const sections = document.querySelectorAll("section");
const navLinks = document.querySelectorAll(".menu a");

let ticking = false;

function onScroll() {
    const scrollTop = window.scrollY;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;

    if (progressBar) {
        progressBar.style.width =
            (docHeight > 0 ? (scrollTop / docHeight) * 100 : 0) + "%";
    }

    if (nav) {
        nav.classList.toggle("scrolled", scrollTop > 40);
    }

    let current = "";
    sections.forEach(section => {
        if (scrollTop >= section.offsetTop - 140) current = section.id;
    });

    navLinks.forEach(link => {
        link.classList.toggle("active", link.getAttribute("href") === `#${current}`);
    });

    ticking = false;
}

window.addEventListener("scroll", () => {
    if (!ticking) {
        requestAnimationFrame(onScroll);
        ticking = true;
    }
}, { passive: true });

/* ====================================================
   MOBILE MENU
==================================================== */
const burger = document.getElementById("burger");
const menu = document.querySelector(".menu");

function closeMenu() {
    if (!menu) return;
    menu.classList.remove("active");
    if (burger) burger.setAttribute("aria-expanded", "false");
    document.body.style.overflow = "";
}

if (burger && menu) {
    burger.addEventListener("click", () => {
        const isActive = menu.classList.toggle("active");
        burger.setAttribute("aria-expanded", String(isActive));
        document.body.style.overflow = isActive ? "hidden" : "";
    });

    menu.querySelectorAll("a").forEach(link => {
        link.addEventListener("click", closeMenu);
    });
}

